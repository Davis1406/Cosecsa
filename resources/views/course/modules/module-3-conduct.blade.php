  <p style="color:var(--muted)">Tap a situation to see the answer.</p>
  <div>
  <details><summary>The candidate is struggling with English. What can you do?</summary><div>You may paraphrase or clarify the question using simple, neutral language, without giving clues to the answer. Document significant language difficulties on the marking sheet.</div></details>
  <details><summary>The candidate gives a very long answer. How do you redirect them?</summary><div>Gently bring the candidate back to the question being assessed. Avoid unnecessary discussion, as examination time is limited.</div></details>
  <details><summary>Your co-examiner is asking too many questions. What should you do?</summary><div>Politely intervene and return to the agreed questions and examination format. Ensure the candidate has sufficient opportunity to speak and demonstrate competence.</div></details>
  <details><summary>The patient actor is behaving differently for different candidates. What should you do?</summary><div>Remind the actor discreetly of the agreed role and expected responses. If the inconsistency continues, inform the invigilator or examination lead.</div></details>
  <details><summary>You know the candidate personally. What should you do?</summary><div>Do not allow your prior knowledge or relationship to influence your assessment. Declare any potential conflict of interest and follow COSECSA procedures.</div></details>
  <details><summary>The candidate gives an answer different from the one you expected. How should you score it?</summary><div>Assess the answer against the agreed marking criteria, not your personal preference. A reasonable alternative answer should be discussed with the other examiner or examination lead when necessary.</div></details>
  </div>

