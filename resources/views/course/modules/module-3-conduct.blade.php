<div class="topic" data-i="4"><button class="th" type="button" aria-expanded="false"><span class="ic"><svg><use href="#i6"/></svg></span><span><b>Your duties</b><small>Before, during and after the examination</small></span><span class="ch"></span></button><div class="pn">
  <div class="duty">
    <div class="cs-card"><h3>Before the examination</h3><ul>
      <li>Read the scenario and proposed answers carefully. Where possible, agree with other examiners giving the same scenario how to score possible answers.</li>
      <li>Treat your commitment as a priority and honour it.</li>
      <li>Take part in all video teaching and briefings.</li></ul></div>
    <div class="cs-card"><h3>During the examination</h3><ul>
      <li>Be early at your meetings and at your station.</li>
      <li>Keep strictly to the time: stop and start on time.</li>
      <li>Hold fellow examiners to a high standard of professionalism.</li></ul></div>
    <div class="cs-card"><h3>After the examination</h3><ul><li>Attend the post-examination reports and discussions.</li></ul></div>
  </div>

</div></div>

<div class="topic" data-i="5"><button class="th" type="button" aria-expanded="false"><span class="ic"><svg><use href="#i3"/></svg></span><span><b>Patients and actors</b><small>Briefing and consistency</small></span><span class="ch"></span></button><div class="pn">
  <div class="video"><div class="play"></div><small>Video: Exam stations with patients</small></div>
  <ul class="pts">
    <li>Brief the patient or actor on their role. Make sure they are comfortable and can take breaks.</li>
    <li>The patient or actor must be consistent for all candidates. If they are over- or under-acting, gently remind them of what they are required to do. Note on the marking sheet any case where the candidate's exam may have been affected.</li>
    <li>If their behaviour is inconsistent, contact the exam invigilator on how to proceed.</li>
  </ul>

</div></div>

