<div class="topic" data-i="0"><button class="th" type="button" aria-expanded="false"><span class="ic"><svg><use href="#i1"/></svg></span><span><b>Purpose and outcomes</b><small>Why this module matters</small></span><span class="ch"></span></button><div class="pn">
  <p class="cs-lead">This module introduces the duties, responsibilities and professional behaviours expected of COSECSA examiners. It is about keeping the examination fair, consistent, respectful and standardised for every candidate.</p>
  <div class="callout"><b>Your behaviour is part of the assessment process.</b></div>
  <details><summary>What you will be able to do (10 outcomes)</summary><div>
  <ol style="margin:0;padding-left:20px;display:flex;flex-direction:column;gap:8px;font-size:15px">
  <li>Apply the agreed examination standard consistently throughout the examination and across all candidates.</li>
  <li>Assess candidates fairly and objectively, without discrimination or inappropriate influence from personal characteristics, background or prior knowledge of the candidate.</li>
  <li>Use the examination format, questions, marking criteria and time limits as instructed, while allowing candidates a fair opportunity to demonstrate their knowledge, skills and communication abilities.</li>
  <li>Communicate with candidates appropriately, being attentive, respectful, encouraging and professional without coaching, intimidating, patronizing or unnecessarily influencing their performance.</li>
  <li>Use appropriate clarification or prompting when permitted, particularly where language or communication difficulties may affect understanding, while maintaining the integrity and standardization of the examination.</li>
  <li>Manage candidate and patient-actor interactions appropriately, ensuring consistency, dignity, comfort and fairness for all candidates.</li>
  <li>Work effectively with fellow examiners, including preparation, calibration, consistent scoring, appropriate intervention and maintaining professional standards throughout the examination.</li>
  <li>Recognize and manage situations that may affect examiner judgement or examination fairness, including examiner bias, conflicts of interest, fatigue, distractions and inconsistent examiner behavior.</li>
  <li>Maintain examination security, confidentiality and professional conduct before, during and after the examination.</li>
  <li>Participate fully in examiner preparation, briefing, examination activities and post-examination review, recognizing that every examiner contributes to the reliability, validity and integrity of the COSECSA examination process.</li></ol></div></details>

</div></div>

<div class="topic" data-i="1"><button class="th" type="button" aria-expanded="false"><span class="ic"><svg><use href="#i7"/></svg></span><span><b>Key principles</b><small>Eight rules for every examiner</small></span><span class="ch"></span></button><div class="pn">
  <ol class="p">
    <li>Assess the candidate, not the person</li>
    <li>Apply the agreed standard, not your personal standard</li>
    <li>Give every candidate the same opportunity to demonstrate competence</li>
    <li>Let the candidate do the talking</li>
    <li>Do not coach, lead or unnecessarily influence the candidate</li>
    <li>Keep within the agreed examination time and format</li>
    <li>When uncertain, follow the examination guidance and ask the appropriate examination lead</li>
    <li>Your behaviour as an examiner is part of the assessment process</li>
  </ol>

</div></div>

